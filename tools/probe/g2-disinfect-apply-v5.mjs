let totalHits = 0
const report = []
const pending = []
const missed = []

for (const [file, pairs] of Object.entries(M)) {
  let text
  try {
    text = readFileSync(file, 'utf8')
  } catch {
    missed.push({ file, kind: '读不到', oldStr: '(文件不存在或不可读)' })
    continue
  }
  for (const [oldStr, newStr, kind] of pairs) {
    const n = text.split(oldStr).length - 1
    if (n === 0) {
      missed.push({ file, kind, oldStr })
      continue
    }
    totalHits += n
    report.push({ file, kind, n, oldStr, newStr })
    text = text.split(oldStr).join(newStr)
  }
  pending.push({ file, text })
}

