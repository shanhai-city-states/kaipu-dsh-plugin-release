/**
 * 山海·开铺 · 场地插件 · 宿主侧边栏的**品牌名**
 * =====================================================================
 *
 * ── ★★ 先说清这为什么**不是**"越界改宿主"──────────────────────────
 *
 *   宿主（DSH）的侧边栏左上角那一块，是由**两个公开座位**拼的：
 *
 *     · `sidebar.brand.mark` —— 图形标，座位自带 fallback = `FishLogo`（那条鱼）
 *     · `sidebar.brand.name` —— 文字名，座位自带 fallback = `t('brand.localBuild')`
 *       （zh 下就是「DSH 本地构建」）
 *
 *   官方自己的**品牌插件**就是这两个座位的示例占用者 —— 它也只是
 *   `ctx.slots.register({ name: 'sidebar.brand.name' }, …)`，
 *   而且只在 `DSH_CLIENT_BUILD_PROFILE === 'official'` 时注册。
 *   ⇒ **占用座位是"坐在席位上的客人"，不是"拆宿主房梁"。**
 *     这条与「零宿主改动」不冲突：我们一个 `deepseek-harness` 的字都没改。
 *
 * ── ★★ 措辞边界（2026-10-07 · 工坊 `071-review` §二 裁定）────────────────
 *
 *   本文件曾写着官方插件与宿主模块的**包名 / 源码路径**（两处），现已中性化。理由
 *   （工坊原话比我方给的硬一层）：
 *     > 要删的理由不是「消毒口径不区分谁的内部」—— **是「这不是我们的东西」**。
 *     > 我们开源，讲的是**「我们怎么做的」**；引用**宿主源码路径 / 官方插件的内部包名**，
 *     > 讲的是**「它内部长什么样」**。**后者不是我们的资产。**
 *   ⇒ 所以下面凡是讲**机制与后果**（座位类型、会怎样 throw、我们因此怎么防）的，**都留着**；
 *     凡是**指路到人家源码**的，**一概不写**。**论证一点没少，只是去掉"我是从哪读到的"。**
 *   ★ 这条边界由 `tools/check-host-internals.mjs` 看护（形态式扫描，不靠人眼）。
 *
 * ── ★ 只占 `name`，不占 `mark`（发起人 2026-10-07 定）────────────────
 *
 *   「头像暂时没想好，就先保持原生头像」⇒ 图形标继续用**宿主原生**的那条鱼。
 *   一个人只坐自己那一格，也免得将来换 logo 要动两处。
 *
 * ── ★★ 注册**必须**包 try/catch —— 这不是套话，是具体会炸 ─────────────
 *
 *   `sidebar.brand.name` 的座位类型是 **single**。宿主对 single 座位的注册处理是：
 *
 *     同 priority 上已经有 occupant ⇒ **throw**
 *     （"single slot … already has a registration … register at a different
 *       priority to shadow it"）
 *
 *   而**在 `apply()` 里抛错 ⇒ 整个 client bundle 加载失败 ⇒ 整站白屏**。
 *   本仓已经用**一次白屏**换来过同类教训（list 座位漏 `id`）。
 *
 *   ⇒ 场景是真实的、而且就在我们自己的机器上会出现：
 *     宿主若是 **official 构建**，官方品牌插件**已经坐在这一格**。
 *     我们**不该去争**：静默退回原生名，比让用户整个界面白掉好得多。
 *     （与侧边栏 `order: 30` 那条同一种姿态 —— **第三方插件不替宿主做决定**。）
 *
 * ── ★ 字号为什么是 13 而不是继承（实测约束，不是审美）────────────────
 *
 *   宿主 `.brandName` 的字号是 **18px / weight 600**。那是给「DSH 本地构建」
 *   这种 6 字以内的名字定的。我们的名字长一倍多，照搬会**撑破侧边栏**
 *   （撑破的表现不是"换行"，是整行被挤出去 / 横向出现滚动条）。
 *   ⇒ 主动降一档并配 `ellipsis`：**先保证装得下，再谈好不好看**。
 *     万一宿主把侧边栏收得更窄，截断也比溢出体面。
 */
import type { ReactElement } from 'react'

/**
 * 坐在宿主 `sidebar.brand.name` 座位上的品牌名。
 *
 * ★ 交接面：座位 owner props 是空的（`SidebarBrandNameOwnerProps` 没有字段）
 *   ⇒ 本组件**不接 props**。宿主自己负责把它套进 `.brandIdentity > .brandName`。
 * ★ `data-kaipu-brand` 是给真机判据用的结构锚点 —— 判据断"侧边栏那个座位上
 *   坐着的是我们"，靠这个锚点找，不靠满页找四个字。
 */
export function KaipuBrandName(): ReactElement {
  return (
    <span
      data-kaipu-brand="1"
      style={{
        display: 'block',
        width: '100%',
        fontSize: 13,
        lineHeight: '24px',
        whiteSpace: 'nowrap',
        overflow: 'hidden',
        textOverflow: 'ellipsis',
      }}
    >
      {/*
        ★ 写成 `{'…'}`（表达式）而**不是**裸的 JSX 文本子节点 —— 实测差异：
          JSX 文本子节点会被 tsc 编成 `"\u5C71\u6D77 …"` 转义序列，
          于是**产物里 grep 不到**这四个字（运行时显示正常，不影响功能）。
          本仓有一个"改完去产物里核对承诺的文案/锚点"的习惯动作 ——
          转义会让那个动作**静默失效**（grep 不到 ⇒ 以为自己漏了，或干脆绕过）。
          ⇒ 用表达式容器，产物里就是原文。

        ★★★ 2026-10-07 改名（原为「山海 · 开铺 · 凉亭 · 场地」）—— 记录**为什么**
             现在只有两个词，免得日后有人"顺手补全"成四段式：

        古茶 `010-2026-10-07-003-古茶-界面维度措辞.md` §二 判原四段式**架构上是错的**：
        **场地是基座，不是与开铺/凉亭并列的项** —— 把「场地」和三个插件并排，
        等于把「操作系统」和「三个 App」并排。发起人 2026-10-07 采纳。

        ⇒ 现名「山海 · 开铺」：**现在只有开铺上线，就不把没上线的东西写进标题。**
          等凉亭、工位都上线后，再升格为「山海 · 场地」，下面挂三个入口。
        ⚠️ 所以**不要**看到名字短了就去"补全" —— 那是**架构判断**，不是省略。
           改名要同时改 `tools/probe/run-view-probe.mjs` 里那条品牌名断言（见该处注释）。
      */}
      {'山海 · 开铺'}
    </span>
  )
}
